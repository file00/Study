// [Title] Basic Structure and Output in C
#include <stdio.h>

int main() {

    // Prints "Hello, World!" and moves the cursor to the next line.
    printf("Hello, World!\n");   

     /*
     * [Important Rules for printf & Output]
     * 1. Content to print must be inside parentheses () and double quotes "".
     * 2. The statement must end with a semicolon ; to prevent syntax errors.
     * 3. '\n' is an escape sequence used for a new line (newline character).
     * *Note: Information Processing Engineer exams strictly check for newlines 
     *        when writing the exact execution output.
     */

    return 0;
}
